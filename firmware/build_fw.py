#!/usr/bin/env python3
"""Assemble sdr_fw.S for the MT7922 WF MCU and emit the driver header (image plus mailbox layout).

The image gets BirriaSDR's PDA trailer: zero padding and a final word that makes the ROM's
download checksum come out to 0.
"""
import argparse
import hashlib
import re
import struct
import subprocess
import tempfile
from pathlib import Path

ENTRY = 0x0091b000  # WM region 0 load address (ILM); the ROM jumps here on FW_START


def checksum(data):
    # PDA word LFSR (BirriaSDR, measured on MT7961)
    state = 0
    for word, in struct.iter_unpack('<I', data):
        parity = (state & 0x10921111).bit_count() & 1
        state = (state >> 1) ^ (parity << 31) ^ word
    return state


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source')
    p.add_argument('header')
    p.add_argument('--cross', default='nds32le-elf-',
                   help='binutils prefix (an nds32 binutils build with gas)')
    for t in ('as', 'ld', 'objcopy'):
        p.add_argument(f'--{t}', dest=t, help=f'path to {t}, overriding --cross')
    a = p.parse_args()
    src = Path(a.source).read_text()
    equ = dict(re.findall(r'^\.equ (\w+), (0x[0-9a-fA-F]+)', src, re.M))
    tool = lambda t: getattr(a, t) or a.cross + t  # noqa: E731
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / 'l.ld').write_text(f'ENTRY(_start)\nSECTIONS {{ .text {ENTRY:#x} : {{ *(.text.entry) *(.text*) }} }}\n')
        subprocess.run([tool('as'), '-EL', '-march=v3', '-mreduced-regs', '-mno-all-relax',
                        '-o', d / 'p.o', a.source], check=True)
        subprocess.run([tool('ld'), '--no-relax', '-T', d / 'l.ld', '-o', d / 'p.elf', d / 'p.o'], check=True)
        subprocess.run([tool('objcopy'), '-O', 'binary', '-j', '.text', d / 'p.elf', d / 'p.bin'], check=True)
        code = (d / 'p.bin').read_bytes()
    if not code or len(code) > 4096 or len(code) % 2:
        raise ValueError('unexpected code size')
    image = code + bytes(-len(code) % 16) + bytes(16)
    image = image[:-4] + struct.pack('<I', checksum(image))
    assert checksum(image) == 0
    sha = hashlib.sha256(image).hexdigest()
    body = '\n'.join('\t' + ', '.join(f'0x{x:02x}' for x in image[i:i + 12]) + ','
                     for i in range(0, len(image), 12))
    mb = '\n'.join(f'#define SDR_{k}\t{int(v, 16):#05x}' for k, v in equ.items() if k.startswith('MB_'))
    Path(a.header).write_text(
        f'/* SPDX-License-Identifier: MIT */\n'
        f'/* Generated by build_fw.py from {Path(a.source).name}, SHA256 {sha} */\n'
        '#ifndef __MT7921_SDR_FW_H\n#define __MT7921_SDR_FW_H\n\n'
        f'#define SDR_ENTRY\t\t{ENTRY:#010x}\n'
        f'#define SDR_MAILBOX\t\t{int(equ["MAILBOX"], 16):#010x}\n'
        f'#define SDR_BOOT_MAGIC\t\t{int(equ["BOOT_MAGIC"], 16):#010x}\n'
        f'#define SDR_RESPONSE_XOR\t{int(equ["RESPONSE_XOR"], 16):#010x}\n'
        f'#define SDR_STOPREG\t\t{int(equ["STOPREG"], 16):#010x}\n'
        f'#define SDR_STOPMAGIC\t\t{int(equ["STOPMAGIC"], 16):#010x}\n\n'
        f'/* Mailbox byte offsets */\n{mb}\n\n'
        f'static const u8 sdr_fw_image[] = {{\n{body}\n}};\n\n#endif\n')
    print(f'{len(code)} code bytes, {len(image)} image bytes, SHA256 {sha}')


if __name__ == '__main__':
    main()
